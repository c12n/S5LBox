#ifndef S5LBOX_S5L8920_SDHC_H
#define S5LBOX_S5L8920_SDHC_H
#include <stdbool.h>
#include <stdint.h>

#define S5L8920_SDHC_BASE UINT32_C(0x80000000)
#define S5L8920_SDHC_SIZE 0x1000u

typedef struct {
    uint32_t dma_address,argument;
    uint16_t block_size,block_count,transfer_mode;
    uint16_t normal_status,error_status,normal_enable,error_enable;
    uint16_t normal_signal,error_signal;
    uint8_t host_control,timeout,reset_pending;
    bool initialized;
    uint16_t clock_control;
    bool clock_stable;
} s5l8920_sdhc_t;

/* Explicit cold functional state, not a measured power-on state or continuous
 * firmware handoff. Call on zeroed storage; repeated init preserves state.
 * No card, command engine, clock source or interrupt connection is supplied.
 * Calls are serialized. The owner controls lifetime and clock availability. */
bool s5l8920_sdhc_init(s5l8920_sdhc_t *s);
/* Exact register widths only: words 00/08; halfwords 04/06/0C/2C/30/32/34/36/38/3A;
 * bytes 28/2E/2F. Unknown selectors, reserved values and other widths refuse.
 * Preparation registers store state but cannot issue a command. Status is W1C;
 * no events are generated by this partial component. Present/card state,
 * responses, FIFO, power and capabilities remain unavailable.
 * Clock2C stores internal-enable bit0, card-clock request bit2 and the older
 * eight-bit divider (bypass or power-of-two divisor2..256 only). Bit1 reports
 * hardware readiness; writes to that read-only bit are ignored. Enabling,
 * disabling or changing divider clears readiness. Card-clock request does
 * not supply a card, a physical output clock or command/data completion.
 * Software reset bits 0/1/2 select all/command/data. A nonzero request latches
 * until explicit service. Pending reset permits only reads and zero/idempotent
 * reset writes. Refusal leaves device state and read output unchanged. */
bool s5l8920_sdhc_read(const s5l8920_sdhc_t *s,uint32_t offset,unsigned size,uint32_t *value);
bool s5l8920_sdhc_write(s5l8920_sdhc_t *s,uint32_t offset,unsigned size,uint32_t value);
/* One functional reset service, independent of CPU execution and reads. With
 * no supplied controller clock, pending work is retained. All reset clears
 * every modeled register; command/data resets clear their normal-status
 * domains and preserve preparation and error/enable state. No command/card
 * completion or physical duration is inferred. Bus gating belongs to the
 * owner; this flag controls only progress of pending reset work. */
bool s5l8920_sdhc_service(s5l8920_sdhc_t *s,bool clock_available);
/* Separate functional clock service; the reset service above never calls it.
 * With no pending reset, readiness follows internal-enable and the supplied
 * source availability. Absent source clears readiness without erasing control
 * requests. Pending reset pauses this service; all reset clears clock state,
 * command/data resets preserve it. No frequency, phase or physical settling
 * time is inferred. Reads/writes never establish readiness. */
bool s5l8920_sdhc_clock_service(s5l8920_sdhc_t *s,bool source_available);
#endif
